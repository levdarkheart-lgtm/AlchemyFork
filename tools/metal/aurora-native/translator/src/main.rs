//! Offline-only exact pinned WGSL -> MSL generation. No viewer Rust dependency.
use std::{fs,path::PathBuf};
use naga::{back::msl,proc::{BoundsCheckPolicies,BoundsCheckPolicy},valid::{Validator,ValidationFlags,Capabilities}};
fn main() {
 let root=PathBuf::from(std::env::args().nth(1).expect("repository root"));
 let vendor=root.join("tools/metal/aurora-evaluation/vendor/aurora/shaders/fsr");
 let output=root.join("indra/almetal/shaders/aurora");
 let common=fs::read_to_string(vendor.join("common.wgsl")).unwrap();
 let mut header=String::from("// Generated by tools/metal/aurora-native/translator; do not edit.\n#pragma once\nnamespace alAuroraShaders {\n");
 for name in ["prepare_inputs","pyramids","reactivity","accumulate"] {
  let source=format!("{common}\n{}",fs::read_to_string(vendor.join(format!("{name}.wgsl"))).unwrap());
  let module=naga::front::wgsl::parse_str(&source).unwrap_or_else(|e|panic!("{}",e.emit_to_string(&source)));
  let info=Validator::new(ValidationFlags::all(),Capabilities::empty()).validate(&module).unwrap();
  let mut map=msl::EntryPointResourceMap::new();
  for ep in &module.entry_points {
   let mut resources=msl::BindingMap::new();
   for (_,v) in module.global_variables.iter() {
    if let Some(b)=v.binding {
     let mut target=msl::BindTarget::default();
     match &module.types[v.ty].inner {
      naga::TypeInner::Image{..}=>target.texture=Some(b.binding as u8),
      naga::TypeInner::Sampler{..}=>target.sampler=Some(msl::BindSamplerTarget::Resource(0)),
      _=>{ target.buffer=Some(b.binding as u8); target.mutable=matches!(v.space,naga::AddressSpace::Storage{access} if access.contains(naga::StorageAccess::STORE)); }
     }
     resources.insert(b,target);
    }
   }
   map.insert(ep.name.clone(),msl::EntryPointResources{resources,sizes_buffer:Some(30),..Default::default()});
  }
  let options=msl::Options { lang_version:(4,0),per_entry_point_map:map,fake_missing_bindings:false,
   bounds_check_policies:BoundsCheckPolicies{index:BoundsCheckPolicy::Restrict,buffer:BoundsCheckPolicy::Restrict,image_load:BoundsCheckPolicy::Restrict,binding_array:BoundsCheckPolicy::Unchecked},..Default::default() };
  let (msl,reflection)=msl::write_string(&module,&info,&options,&msl::PipelineOptions::default()).unwrap();
  for (ep,translated) in module.entry_points.iter().zip(reflection.entry_point_names) {
   let translated=translated.expect("Naga entry-point binding reflection");
   header.push_str(&format!("inline constexpr const char* {name}_{} = {translated:?};\n",ep.name));
   println!("{name}: {} -> {translated}",ep.name);
  }
  let msl=format!("// GENERATED from Aurora ee458fbf1d95e98c5b3a55c0027a523bb28d7e7f / pinned Naga 6c13013.\n// FidelityFX SDK 1.1.4 / MIT: see tools/metal/aurora-evaluation/vendor/aurora/NOTICE.md.\n{msl}");
  fs::write(output.join(format!("{name}.metal")),&msl).unwrap();
  header.push_str(&format!("inline constexpr const char* {name} = R\"AURORA({msl})AURORA\";\n"));
 }
 header.push_str("}\n");fs::write(output.join("sources.h"),header).unwrap();
}
